"""Execute the pilot's 60 programs and their own `test` blocks, in both modes.

Writes `results.md` and `results.json`. The tests are the models' own, so passing them shows
the program does what its author meant, not that it solves the task.
"""

import json
from collections import Counter
from pathlib import Path

from transpile import run

HERE = Path(__file__).parent
RUNS = HERE.parent.parent / "pilot" / "runs"

# Lines a test may run before it is stopped as a timeout; a convenience, not a guard.
BUDGET = 200_000


def last_line(text: str) -> str:
    lines = [line for line in text.strip().splitlines() if line.strip()]
    return lines[-1].strip() if lines else ""


def main() -> None:
    rows = []
    for program in sorted(RUNS.glob("*/*.x")):
        run_name = program.parent.name
        source = program.read_text(encoding="utf-8")
        path = f"{run_name}/{program.name}"
        modes = {
            mode: run(source, run_name[0], path=path, mode=mode, budget=BUDGET)
            for mode in ("lotml", "python")
        }
        rows.append(
            {
                "run": run_name,
                "task": program.stem,
                "error": modes["lotml"].error,
                "tests": {
                    name: {
                        "lotml": outcome,
                        "python": modes["python"].tests.get(name),
                        "detail": last_line(modes["lotml"].tracebacks.get(name, "")),
                    }
                    for name, outcome in modes["lotml"].tests.items()
                },
            }
        )
    (HERE / "results.json").write_text(json.dumps(rows, indent=2) + "\n", "utf-8")

    lines = [
        "# Pilot programs, executed",
        "",
        "Generated by `pilot.py`. Each program in `research/pilot/runs/` is transpiled to",
        "Python and its own `test` blocks are run, once with lotml's semantics (`lotml`)",
        "and once with Python's (`python`): references, truthiness and Python's `or`.",
        "",
        "## Per run",
        "",
        "| run | programs | ran | tests | pass, lotml | pass, python | all tests pass, lotml |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for run_name in sorted({r["run"] for r in rows}):
        group = [r for r in rows if r["run"] == run_name]
        ran = [r for r in group if r["error"] is None]
        tests = [t for r in ran for t in r["tests"].values()]
        green = sum(
            1
            for r in ran
            if r["tests"] and all(t["lotml"] == "pass" for t in r["tests"].values())
        )
        lines.append(
            f"| {run_name} | {len(group)} | {len(ran)} | {len(tests)} "
            f"| {sum(t['lotml'] == 'pass' for t in tests)} "
            f"| {sum(t['python'] == 'pass' for t in tests)} | {green} |"
        )

    lines += [
        "",
        "## Programs that did not run",
        "",
        "| run | task | reason |",
        "| --- | --- | --- |",
    ]
    for row in rows:
        if row["error"] is not None:
            lines.append(f"| {row['run']} | {row['task']} | {row['error']} |")

    lines += [
        "",
        "## Tests that fail under lotml's semantics",
        "",
        "| run | task | test | outcome | python | last line |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        for name, test in row["tests"].items():
            if test["lotml"] != "pass":
                detail = test["detail"].replace("|", "\\|")
                lines.append(
                    f"| {row['run']} | {row['task']} | {name} | {test['lotml']} "
                    f"| {test['python']} | `{detail}` |"
                )

    lines += [
        "",
        "## Tests whose outcome depends on the semantics",
        "",
        "| run | task | test | lotml | python |",
        "| --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        for name, test in row["tests"].items():
            if test["lotml"] != test["python"]:
                lines.append(
                    f"| {row['run']} | {row['task']} | {name} | {test['lotml']} | {test['python']} |"
                )

    differ = Counter(
        (test["lotml"] == "pass", test["python"] == "pass")
        for row in rows
        for test in row["tests"].values()
        if test["lotml"] != test["python"]
    )
    lines += [
        "",
        "## Where the semantics decide the outcome",
        "",
        f"- passes under lotml, fails under Python: {differ[(True, False)]}",
        f"- passes under Python, fails under lotml: {differ[(False, True)]}",
        f"- fails under both, differently: {differ[(False, False)]}",
        "",
    ]
    (HERE / "results.md").write_text("\n".join(lines), "utf-8")


if __name__ == "__main__":
    main()
