"""Does a Python AST carrying lotml positions make tracebacks point at the .lotml file?"""

import ast
import linecache
import sys
import traceback
import types
from pathlib import Path

RATIO_SOURCE = "fn ratio(d: int?) -> int:\n    return 10 // (d ?? 0)\n"

# What a transpiler would print for RATIO_SOURCE, prelude included.
RATIO_PYTHON = (
    "from __future__ import annotations\n"
    "def ratio(d: int | None) -> int:\n"
    "    return 10 // (d if d is not None else 0)\n"
)


def python_tree() -> ast.Module:
    """The control: RATIO_PYTHON parsed, so every node keeps its Python position."""
    return ast.parse(RATIO_PYTHON)


def at[N: ast.AST](node: N, line: int, col: int, end_col: int, end_line: int = 0) -> N:
    """Place `node` at a lotml span; columns are 0-based UTF-8 offsets, as in `ast`."""
    node.lineno, node.col_offset = line, col
    node.end_lineno, node.end_col_offset = end_line or line, end_col
    return node


def ratio_tree() -> ast.Module:
    """The AST a transpiler emits for RATIO_SOURCE, every node at its lotml position.

    `d ?? 0` becomes `d if d is not None else 0`; the nodes with no lotml text of their
    own take the span of the `??` expression they implement.
    """

    def d(col: int = 18) -> ast.Name:
        return at(ast.Name("d", ast.Load()), 2, col, col + 1)

    absent = at(
        ast.Compare(d(), [ast.IsNot()], [at(ast.Constant(None), 2, 18, 24)]), 2, 18, 24
    )
    default = at(ast.IfExp(absent, d(), at(ast.Constant(0), 2, 23, 24)), 2, 18, 24)
    body = at(
        ast.Return(
            at(
                ast.BinOp(at(ast.Constant(10), 2, 11, 13), ast.FloorDiv(), default),
                2,
                11,
                25,
            )
        ),
        2,
        4,
        25,
    )
    optional = at(
        ast.BinOp(
            at(ast.Name("int", ast.Load()), 1, 12, 15),
            ast.BitOr(),
            at(ast.Constant(None), 1, 15, 16),
        ),
        1,
        12,
        16,
    )
    function = ast.FunctionDef(
        name="ratio",
        args=ast.arguments(args=[at(ast.arg("d", optional), 1, 9, 16)]),
        body=[body],
        decorator_list=[],
        returns=at(ast.Name("int", ast.Load()), 1, 21, 24),
        type_params=[],
    )
    return ast.Module([at(function, 1, 0, 25, end_line=2)], type_ignores=[])


def load_module(tree: ast.Module, path: Path, source: str | None = None):
    """Compile `tree` as if it came from `path`; `source` stands in for a missing file."""
    if source is not None:
        linecache.cache[str(path)] = (
            len(source),
            None,
            source.splitlines(True),
            str(path),
        )
    code = compile(ast.fix_missing_locations(tree), str(path), "exec")
    module = types.ModuleType(path.stem)
    module.__file__ = str(path)
    exec(code, module.__dict__)  # noqa: S102
    return module


def traceback_text(tree: ast.Module, path: Path) -> str:
    try:
        load_module(tree, path, source=RATIO_SOURCE).ratio(None)
    except ZeroDivisionError as error:
        failure = traceback.TracebackException.from_exception(error)
        frame = "".join(traceback.format_list(failure.stack[-1:]))
        text = frame + "".join(failure.format_exception_only())
        return text.replace(str(path.parent), "<dir>")
    raise AssertionError("ratio(None) must divide by zero")


def main() -> None:
    here = Path(__file__).parent
    control = traceback_text(python_tree(), here / "control" / "ratio.lotml")
    mapped = traceback_text(ratio_tree(), here / "mapped" / "ratio.lotml")
    (here / "results.md").write_text(
        "\n".join(
            [
                "# Tracebacks through a Python AST",
                "",
                (
                    f"Generated by `tracebacks.py` on CPython {sys.version.split()[0]}."
                    " The lotml source, compiled as `ratio.lotml`:"
                ),
                "",
                "```",
                RATIO_SOURCE.rstrip(),
                "```",
                "",
                "## Control: the transpiled Python's own positions",
                "",
                "```",
                control.rstrip(),
                "```",
                "",
                "## Every node at its lotml position",
                "",
                "```",
                mapped.rstrip(),
                "```",
                "",
            ]
        ),
        "utf-8",
    )


if __name__ == "__main__":
    main()
