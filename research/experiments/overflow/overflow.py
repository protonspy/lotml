"""What lotml's i64 overflow semantics costs on the Python target.

Python integers never overflow, so the transpiler has to emit the check. Each strategy below
is code a transpiler could emit; the benchmark times it against plain Python arithmetic,
which is what giving up the single semantics would buy.
"""

import platform
import sys
import timeit
from pathlib import Path

MIN, MAX = -(2**63), 2**63 - 1
SPAN, BIAS = 2**64, 2**63


def trap(value: int) -> int:
    """Return `value` if it fits in i64; otherwise fail, as lotml does on every target."""
    if MIN <= value <= MAX:
        return value
    raise OverflowError(f"i64 overflow: {value}")


def wrap(value: int) -> int:
    """Two's-complement wrapping, what `wrapping_add` and friends return."""
    return ((value + BIAS) % SPAN) - BIAS


SETUP = """
from overflow import trap, wrap, MIN, MAX, SPAN, BIAS
a, b = 123_456_789, 987
data = list(range(1, 1001))
def overflow(value):
    raise OverflowError(value)
"""

# What the transpiler could emit for `r = a op b`; `{op}` is `+` or `*`.
EXPRESSIONS = {
    "plain": "r = a {op} b",
    "inline trap": "r = a {op} b\nif r > MAX or r < MIN:\n    overflow(r)",
    "walrus trap": "r = s if MIN <= (s := a {op} b) <= MAX else overflow(s)",
    "helper trap": "r = trap(a {op} b)",
    "inline wrap": "r = (a {op} b + BIAS) % SPAN - BIAS",
    "helper wrap": "r = wrap(a {op} b)",
}

# The same strategies inside a loop summing 1..1000, which never overflows.
LOOPS = {
    "plain": "t = 0\nfor x in data:\n    t = t + x",
    "inline trap": (
        "t = 0\nfor x in data:\n    t = t + x\n    if t > MAX or t < MIN:\n        overflow(t)"
    ),
    "walrus trap": (
        "t = 0\nfor x in data:\n    t = s if MIN <= (s := t + x) <= MAX else overflow(s)"
    ),
    "helper trap": "t = 0\nfor x in data:\n    t = trap(t + x)",
    "inline wrap": "t = 0\nfor x in data:\n    t = (t + x + BIAS) % SPAN - BIAS",
    "helper wrap": "t = 0\nfor x in data:\n    t = wrap(t + x)",
}


def best_time(statement: str, number: int, repeat=7) -> float:
    timer = timeit.Timer(statement, setup=SETUP)
    return min(timer.repeat(repeat=repeat, number=number)) / number


def main() -> None:
    here = Path(__file__).parent
    sys.path.insert(0, str(here))
    expression_base = {op: best_time(f"r = a {op} b", 1_000_000) for op in "+*"}
    loop_base = best_time(LOOPS["plain"], 2_000)
    lines = [
        "# Overflow on the Python target",
        "",
        (
            f"Generated by `overflow.py` on CPython {platform.python_version()},"
            f" {platform.system()} {platform.machine()}. Best of 7 runs, relative to"
            " plain Python arithmetic, which never overflows. No strategy takes its"
            " overflow branch: what is measured is the cost of checking, not of failing."
        ),
        "",
        "| strategy | `r = a + b` | `r = a * b` | loop `t = t + x` |",
        "| --- | ---: | ---: | ---: |",
    ]
    for name, template in EXPRESSIONS.items():
        cells = [
            best_time(template.format(op=op), 1_000_000) / expression_base[op]
            for op in "+*"
        ]
        cells.append(best_time(LOOPS[name], 2_000) / loop_base)
        lines.append(f"| {name} | " + " | ".join(f"{c:.2f}×" for c in cells) + " |")
    (here / "results.md").write_text("\n".join(lines) + "\n", "utf-8")


if __name__ == "__main__":
    main()
