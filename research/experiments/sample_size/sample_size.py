"""Paired tasks needed to tell two syntax variants apart, by McNemar's test.

The harness compares two variants on the same tasks; a pair is discordant when one variant
passes and the other fails. `p10` and `p01` are the probabilities of the two kinds of
discordant pair, so `p10 + p01` is the discordant fraction and `p10 - p01` the difference
in pass@1. The harness table uses Connor's normal approximation; this checks it against the
power of the exact test the harness would actually run.
"""

import math
import random
from functools import cache
from pathlib import Path
from statistics import NormalDist

ALPHA = 0.05
POWER = 0.80


def connor_n(discordant: float, delta: float, alpha=ALPHA, power=POWER) -> int:
    """Connor (1987): n = (z_a * sqrt(p) + z_b * sqrt(p - delta^2))^2 / delta^2."""
    z_alpha = NormalDist().inv_cdf(1 - alpha / 2)
    z_beta = NormalDist().inv_cdf(power)
    root = z_alpha * math.sqrt(discordant) + z_beta * math.sqrt(discordant - delta**2)
    return math.ceil(root**2 / delta**2)


@cache
def mcnemar_p(b: int, c: int) -> float:
    """Two-sided exact McNemar p-value: a binomial test on the discordant pairs."""
    m = b + c
    if m == 0:
        return 1.0
    tail = sum(math.comb(m, i) for i in range(min(b, c) + 1))
    return min(1.0, 2 * tail / 2**m)


@cache
def boundary(m: int, alpha=ALPHA) -> int:
    """The largest k with p(k, m - k) <= alpha, or -1: reject when b <= k or b >= m - k."""
    k = -1
    while k + 1 < m - (k + 1) and mcnemar_p(k + 1, m - k - 1) <= alpha:
        k += 1
    return k


def binomial_pmf(k: int, n: int, p: float) -> float:
    if p in (0.0, 1.0):
        return float(k == round(n * p))
    log = math.lgamma(n + 1) - math.lgamma(k + 1) - math.lgamma(n - k + 1)
    return math.exp(log + k * math.log(p) + (n - k) * math.log1p(-p))


def exact_power(n: int, p10: float, p01: float, alpha=ALPHA) -> float:
    """P(exact test rejects), summed over the number m of discordant pairs."""
    discordant = p10 + p01
    if discordant == 0:
        return 0.0
    share = p10 / discordant
    power = 0.0
    for m in range(n + 1):
        k = boundary(m, alpha)
        if k < 0:
            continue
        reject = sum(binomial_pmf(b, m, share) for b in range(k + 1))
        reject += sum(binomial_pmf(b, m, share) for b in range(m - k, m + 1))
        power += binomial_pmf(m, n, discordant) * reject
    return power


def simulated_power(
    n: int, p10: float, p01: float, trials: int, rng: random.Random, alpha=ALPHA
) -> float:
    """The same power by Monte Carlo: draw the discordant counts, run the exact test."""
    rejected = 0
    for _ in range(trials):
        b = rng.binomialvariate(n, p10)
        c = rng.binomialvariate(n - b, p01 / (1 - p10))
        rejected += mcnemar_p(b, c) <= alpha
    return rejected / trials


def smallest_n(p10: float, p01: float, start: int, target=POWER, stable=20) -> int:
    """The smallest n from which exact power stays >= target for `stable` more tasks.

    Exact tests have a sawtooth power curve, so one n reaching the target is not enough.
    """
    n = start
    while not all(exact_power(n + i, p10, p01) >= target for i in range(stable)):
        n += 1
    return n


def main() -> None:
    rows = [(0.20, 0.10), (0.10, 0.05), (0.30, 0.10), (0.20, 0.05), (0.40, 0.20)]
    lines = [
        "# McNemar sample size",
        "",
        "Generated by `sample_size.py`. Two-sided, alpha 0.05, target power 0.80. `n` is",
        "paired tasks; one sample per task per variant.",
        "",
        (
            "| discordant | difference | Connor n | exact power at Connor n "
            "| simulated (20k) | smallest n, exact test |"
        ),
        "| ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    rng = random.Random(2026)
    for discordant, delta in rows:
        p10, p01 = (discordant + delta) / 2, (discordant - delta) / 2
        n = connor_n(discordant, delta)
        exact = exact_power(n, p10, p01)
        simulated = simulated_power(n, p10, p01, trials=20_000, rng=rng)
        needed = smallest_n(p10, p01, start=int(n * 0.9))
        lines.append(
            f"| {discordant:.0%} | {delta * 100:.0f} points | {n} | {exact:.3f} "
            f"| {simulated:.3f} | {needed} |"
        )
    (Path(__file__).parent / "results.md").write_text("\n".join(lines) + "\n", "utf-8")


if __name__ == "__main__":
    main()
