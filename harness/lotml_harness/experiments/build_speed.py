"""How long a small native build takes, step by step (plans/build-and-check-speed.md, tasks 1.1
and 1.2; docs/wiki/pages/compiler-performance.md). One benchmark program is compiled by the LLVM
backend, then built at `-O0` and `-O2` by the runner `cargo run --example build_time`: the
runtime compiled on its own, the program's IR on its own, the two objects linked, and the whole
build as `lotml build` runs it.

Each measurement is kept under a label in `results/build-speed/<label>.json`, and the report
`results/build-speed.md` shows every label recorded, so a measurement taken before a change stays
beside the one taken after it.

    python -m lotml_harness.experiments.build_speed <label>
"""

import json
import platform
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass
from datetime import UTC, datetime

from lotml_harness import ROOT
from lotml_harness.experiments.benchmarks import BENCHMARKS
from lotml_harness.experiments.phase1 import RESULTS

RECORDS = RESULTS / "build-speed"
REPORT = RESULTS / "build-speed.md"
PROGRAM = BENCHMARKS / "fib.lotml"
LABEL = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]*")
"""What a label may be: it names a file in `RECORDS`."""
RUNS = 5
"""Runs of each step; the fastest is kept, the one least disturbed by the rest of the machine."""
LEVELS = ("-O0", "-O2")
STEPS = {
    "runtime": "the runtime's `lotml.c` compiled on its own",
    "program": "the program's LLVM IR compiled on its own",
    "link": "the two objects linked",
    "build": "the whole build, as `lotml build` runs it",
    "cold": "the whole build with an empty runtime cache",
    "warm": "the whole build again, the runtime's object taken from the cache",
}


@dataclass
class Record:
    label: str
    compiler: str
    program: str
    seconds: dict[tuple[str, str], float]
    """The fastest run of each level and step."""
    taken: str = ""
    """When it was measured, in UTC: the report shows the records in that order."""
    system: str = ""
    """The operating system and machine it was measured on."""

    def share(self, level: str) -> float | None:
        """How much of the whole build the runtime's compile is, at `level`."""
        return self._ratio(level, "runtime", "build")

    def warm(self, level: str) -> float | None:
        """How much of a build with an empty cache a build with a filled one takes, at `level`."""
        return self._ratio(level, "warm", "cold")

    def _ratio(self, level: str, part: str, whole: str) -> float | None:
        a, b = self.seconds.get((level, part)), self.seconds.get((level, whole))
        if a is None or not b:
            return None
        return a / b


def parse(label: str, lines: list[str], taken: str = "", system: str = "") -> Record:
    """A record from the runner's JSON lines, keeping each step's fastest run."""
    compiler, program, seconds = "", "", {}
    for line in lines:
        row = json.loads(line)
        if "compiler" in row:
            compiler, program = row["compiler"], row["program"]
            continue
        seconds[(row["level"], row["step"])] = min(row["seconds"])
    return Record(label, compiler, program, seconds, taken, system)


def dump(record: Record) -> str:
    rows = [{"level": lv, "step": st, "seconds": s} for (lv, st), s in record.seconds.items()]
    data = {
        "label": record.label,
        "compiler": record.compiler,
        "program": record.program,
        "taken": record.taken,
        "system": record.system,
        "rows": rows,
    }
    return json.dumps(data, indent=2) + "\n"


def load(text: str) -> Record:
    data = json.loads(text)
    seconds = {(r["level"], r["step"]): r["seconds"] for r in data["rows"]}
    return Record(
        data["label"], data["compiler"], data["program"], seconds, data["taken"], data["system"]
    )


def run(runs: int = RUNS) -> list[str]:
    """The runner's JSON lines for `PROGRAM`."""
    cargo = shutil.which("cargo")
    if cargo is None:
        raise SystemExit("cargo is not on PATH: the build is timed by the LLVM backend's runner")
    ran = subprocess.run(  # noqa: S603 - cargo, on a benchmark of this repository
        [
            cargo,
            "run",
            "--quiet",
            "--release",
            "-p",
            "lotml-llvm",
            "--example",
            "build_time",
            "--",
            str(PROGRAM),
            str(runs),
        ],
        cwd=ROOT / "compiler",
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=True,
    )
    return [line for line in ran.stdout.splitlines() if line.strip()]


def markdown(records: list[Record]) -> str:
    lines = [
        "# Build speed: a small native build, step by step",
        "",
        "Generated by `python -m lotml_harness.experiments.build_speed <label>`. A benchmark",
        "program is compiled by the LLVM backend and built at each level; each step runs",
        f"{RUNS} times and its fastest run is kept. The steps:",
        "",
    ]
    lines += [f"- `{step}`: {what}" for step, what in STEPS.items()]
    lines.append("")
    for record in sorted(records, key=lambda r: r.taken):
        lines += [
            f"## {record.label}",
            "",
            f"`{record.program}`, built by {record.compiler} on {record.system or 'an unnamed'}.",
            "",
            "| step | " + " | ".join(f"{level} (s)" for level in LEVELS) + " |",
            "| --- |" + " ---: |" * len(LEVELS),
        ]
        for step in STEPS:
            cells = [record.seconds.get((level, step)) for level in LEVELS]
            if all(c is None for c in cells):
                continue
            shown = ["" if c is None else f"{c:.3f}" for c in cells]
            lines.append(f"| {step} | " + " | ".join(shown) + " |")
        lines.append("")
        shares = [(level, record.share(level)) for level in LEVELS]
        said = [f"{share:.0%} at `{level}`" for level, share in shares if share is not None]
        if said:
            lines += [f"The runtime's compile is {' and '.join(said)} of the whole build.", ""]
        warm = [(level, record.warm(level)) for level in LEVELS]
        said = [f"{share:.0%} at `{level}`" for level, share in warm if share is not None]
        if said:
            lines += [
                f"A build with the runtime cached takes {' and '.join(said)} of one without.",
                "",
            ]
    return "\n".join(lines)


def main() -> None:
    if len(sys.argv) != 2 or not LABEL.fullmatch(sys.argv[1]):
        raise SystemExit(
            "usage: python -m lotml_harness.experiments.build_speed <label>, "
            "a label of letters, digits, `.`, `_` and `-`"
        )
    taken = datetime.now(UTC).isoformat(timespec="seconds")
    system = f"{platform.system()} {platform.machine()}"
    record = parse(sys.argv[1], run(), taken, system)
    RECORDS.mkdir(parents=True, exist_ok=True)
    (RECORDS / f"{record.label}.json").write_text(dump(record), encoding="utf-8", newline="\n")
    records = [load(p.read_text(encoding="utf-8")) for p in sorted(RECORDS.glob("*.json"))]
    report = markdown(records)
    REPORT.write_text(report, encoding="utf-8", newline="\n")
    sys.stdout.buffer.write(report.encode("utf-8"))


if __name__ == "__main__":
    main()
