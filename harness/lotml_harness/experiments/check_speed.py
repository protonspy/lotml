"""How long a check takes after a one-line body edit (plans/build-and-check-speed.md, task 2.1;
docs/wiki/pages/compiler-performance.md). A large generated file that imports from generated
Python interfaces is checked through `lotml-db` by the runner `cargo run --example check_time`:
from an empty database, and again after one line of one body changed; and, for scale, the file
parsed, its interfaces read and the file checked, each on its own.

Each measurement is kept under a label in `results/check-speed/<label>.json`, and the report
`results/check-speed.md` shows every label recorded, so a measurement taken before a change stays
beside the one taken after it.

    python -m lotml_harness.experiments.check_speed <label>
"""

import json
import platform
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from datetime import UTC, datetime

from lotml_harness import ROOT
from lotml_harness.experiments.build_speed import LABEL
from lotml_harness.experiments.phase1 import RESULTS

RECORDS = RESULTS / "check-speed"
REPORT = RESULTS / "check-speed.md"
RUNS = 5
"""Runs of each step; the fastest is kept, the one least disturbed by the rest of the machine."""
BUDGET = 0.1
"""Seconds the check on every edit may take (docs/wiki/pages/semantic-compiler.md)."""
STEPS = {
    "parse": "the file parsed on its own",
    "interfaces": "the interfaces it imports from read on their own",
    "check": "the parsed file checked on its own",
    "cold": "the file's diagnostics through `lotml-db`, from an empty database",
    "edit": "the file's diagnostics again after one line of one body changed",
}


@dataclass
class Record:
    label: str
    shape: dict[str, int]
    """The file measured: its lines and functions, the modules and signatures it imports from."""
    seconds: dict[str, float]
    """The fastest run of each step."""
    taken: str = ""
    """When it was measured, in UTC: the report shows the records in that order."""
    system: str = ""
    """The operating system and machine it was measured on."""
    runs: dict[str, list[float]] = field(default_factory=dict)
    """Every run of each step, as measured."""

    def share(self, part: str, whole: str) -> float | None:
        """How much of step `whole` step `part` is."""
        a, b = self.seconds.get(part), self.seconds.get(whole)
        if a is None or not b:
            return None
        return a / b


def parse(label: str, lines: list[str], taken: str = "", system: str = "") -> Record:
    """A record from the runner's JSON lines, keeping each step's fastest run."""
    shape, runs = {}, {}
    for line in lines:
        row = json.loads(line)
        if "step" in row:
            runs[row["step"]] = row["seconds"]
        else:
            shape = row
    seconds = {step: min(all_runs) for step, all_runs in runs.items()}
    return Record(label, shape, seconds, taken, system, runs)


def dump(record: Record) -> str:
    data = {
        "label": record.label,
        "shape": record.shape,
        "taken": record.taken,
        "system": record.system,
        "runs": record.runs,
    }
    return json.dumps(data, indent=2) + "\n"


def load(text: str) -> Record:
    data = json.loads(text)
    runs = data["runs"]
    seconds = {step: min(all_runs) for step, all_runs in runs.items()}
    return Record(data["label"], data["shape"], seconds, data["taken"], data["system"], runs)


def run(runs: int = RUNS) -> list[str]:
    """The runner's JSON lines."""
    cargo = shutil.which("cargo")
    if cargo is None:
        raise SystemExit("cargo is not on PATH: the check is timed by `lotml-db`'s runner")
    ran = subprocess.run(  # noqa: S603 - cargo, on a runner of this repository
        [
            cargo,
            "run",
            "--quiet",
            "--release",
            "-p",
            "lotml-db",
            "--example",
            "check_time",
            "--",
            "250",
            str(runs),
        ],
        cwd=ROOT / "compiler",
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=True,
    )
    return [line for line in ran.stdout.splitlines() if line.strip()]


def markdown(records: list[Record]) -> str:
    lines = [
        "# Check speed: a one-line body edit in a large file",
        "",
        "Generated by `python -m lotml_harness.experiments.check_speed <label>`. A generated file",
        "that imports from generated Python interfaces is checked through `lotml-db`; each step",
        f"runs {RUNS} times and its fastest run is kept. The steps:",
        "",
    ]
    lines += [f"- `{step}`: {what}" for step, what in STEPS.items()]
    lines.append("")
    for record in sorted(records, key=lambda r: r.taken):
        shape = record.shape
        system = record.system or "an unnamed machine"
        lines += [
            f"## {record.label}",
            "",
            f"{shape.get('lines', '?')} lines in {shape.get('functions', '?')} functions,"
            f" importing from {shape.get('modules', '?')} modules declaring"
            f" {shape.get('signatures', '?')} functions, on {system}.",
            "",
            "| step | ms |",
            "| --- | ---: |",
        ]
        lines += [
            f"| {step} | {record.seconds[step] * 1000:.2f} |"
            for step in STEPS
            if step in record.seconds
        ]
        lines.append("")
        edit, cold = record.seconds.get("edit"), record.share("edit", "cold")
        if edit is not None and cold is not None:
            within = "within" if edit <= BUDGET else "over"
            lines += [
                f"After the edit the check takes {cold:.0%} of one from an empty database,"
                f" {within} the {BUDGET * 1000:.0f} ms budget.",
                "",
            ]
        read = record.share("interfaces", "edit")
        if read is not None:
            lines += [f"Reading the interfaces alone takes {read:.0%} as long as the edit.", ""]
    return "\n".join(lines)


def main() -> None:
    if len(sys.argv) != 2 or not LABEL.fullmatch(sys.argv[1]):
        raise SystemExit(
            "usage: python -m lotml_harness.experiments.check_speed <label>, "
            "a label of letters, digits, `.`, `_` and `-`"
        )
    taken = datetime.now(UTC).isoformat(timespec="seconds")
    system = f"{platform.system()} {platform.machine()}"
    record = parse(sys.argv[1], run(), taken, system)
    RECORDS.mkdir(parents=True, exist_ok=True)
    (RECORDS / f"{record.label}.json").write_text(dump(record), encoding="utf-8", newline="\n")
    records = [load(p.read_text(encoding="utf-8")) for p in sorted(RECORDS.glob("*.json"))]
    report = markdown(records)
    REPORT.write_text(report, encoding="utf-8", newline="\n")
    sys.stdout.buffer.write(report.encode("utf-8"))


if __name__ == "__main__":
    main()
