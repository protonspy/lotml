"""The benchmarks: programs written in LotML and compiled by the LLVM backend, against the same
programs written in C and built by the same `clang` at the same level (plans/lotml-roadmap.md,
task 4.3; specs/llvm-parity R5.2; docs/wiki/pages/memory-model.md, "Performance target"). Each
run is recorded in `results/benchmarks-llvm.md`, beside the retired C target's last run in
`results/benchmarks.md`.

Numeric, allocation-heavy and sharing-heavy programs are reported apart, as the memory model
asks: the numeric ones are held to 2x C, and the others only reported, where reference counting
is expected to lose to a hand-managed heap. A program the LLVM backend does not compile yet is
named with why.

    python -m lotml_harness.experiments.benchmarks
"""

import json
import shutil
import subprocess
import sys
from dataclasses import dataclass

from lotml_harness import ROOT
from lotml_harness.experiments.phase1 import RESULTS

BENCHMARKS = ROOT / "harness" / "benchmarks"
REPORT = RESULTS / "benchmarks-llvm.md"
RUNS = 7
"""Runs of each program; the fastest is kept, the one least disturbed by the rest of the machine."""
LIMIT = 2.0
"""The most a numeric program may take, as a multiple of its C version."""
KINDS = {
    "mandelbrot": "numeric",
    "sieve": "numeric",
    "collatz": "numeric",
    "fib": "numeric",
    "matmul": "numeric",
    "binarytrees": "allocation",
    "strings": "allocation",
    "wordcount": "allocation",
    "cow": "sharing",
    "shared": "sharing",
}
TITLES = {
    "numeric": "Numeric",
    "allocation": "Allocation-heavy",
    "sharing": "Sharing-heavy",
}


@dataclass
class Result:
    name: str
    kind: str
    c: float
    """Seconds of the C version's fastest run."""
    lotml: float
    same: bool
    """Whether the two print the same."""

    @property
    def ratio(self) -> float:
        return self.lotml / self.c


def parse(lines: list[str]) -> tuple[str, list[Result], list[tuple[str, str]]]:
    """The compiler, each benchmark's result, and each one not compiled yet with why, from the
    runner's JSON lines."""
    compiler, results, refused = "", [], []
    for line in lines:
        row = json.loads(line)
        if "compiler" in row:
            compiler = row["compiler"]
            continue
        if "refused" in row:
            refused.append((row["name"], row["refused"]))
            continue
        results.append(
            Result(
                row["name"],
                KINDS[row["name"]],
                min(row["c"]),
                min(row["lotml"]),
                row["c_out"] == row["lotml_out"],
            )
        )
    return compiler, results, refused


def run(runs: int = RUNS) -> tuple[str, list[Result], list[tuple[str, str]]]:
    """Every benchmark built and run by the LLVM backend's runner, `cargo run --example bench`."""
    cargo = shutil.which("cargo")
    if cargo is None:
        raise SystemExit(
            "cargo is not on PATH: the benchmarks are built by the LLVM backend's runner"
        )
    ran = subprocess.run(  # noqa: S603 - cargo, on the benchmarks of this repository
        [
            cargo,
            "run",
            "--quiet",
            "--release",
            "-p",
            "lotml-llvm",
            "--example",
            "bench",
            "--",
            str(BENCHMARKS),
            str(runs),
        ],
        cwd=ROOT / "compiler",
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=True,
    )
    return parse([line for line in ran.stdout.splitlines() if line.strip()])


def markdown(
    compiler: str, results: list[Result], refused: list[tuple[str, str]] | None = None
) -> str:
    refused = refused or []
    lines = [
        "# Benchmarks: the LLVM target against C",
        "",
        "Generated by `python -m lotml_harness.experiments.benchmarks`. Each program in",
        "`harness/benchmarks/` is written in LotML and in C; the LotML one is compiled by the LLVM",
        f"backend, and both are built by {compiler} at `-O2`. Each runs {RUNS} times and its",
        "fastest run is kept. The LotML programs check every integer operation and index, which",
        "the C ones do not.",
        "",
    ]
    for kind, title in TITLES.items():
        rows = [r for r in results if r.kind == kind]
        if not rows:
            continue
        lines += [f"## {title}", "", "| program | C (s) | LotML (s) | LotML / C | same output |"]
        lines.append("| --- | ---: | ---: | ---: | --- |")
        for r in rows:
            same = "yes" if r.same else "no"
            lines.append(f"| {r.name} | {r.c:.3f} | {r.lotml:.3f} | {r.ratio:.2f}x | {same} |")
        lines.append("")
    if refused:
        lines += ["## Not compiled yet", ""]
        lines += [f"- `{name}`: {why}" for name, why in refused]
        lines.append("")
    numeric = [r for r in results if r.kind == "numeric"]
    over = [r for r in numeric if r.ratio > LIMIT]
    differing = [r for r in results if not r.same]
    missing = [name for name, _ in refused if KINDS.get(name) == "numeric"]
    if numeric and not over and not differing and not missing:
        lines.append(f"The numeric programs are within {LIMIT:g}x C.")
    else:
        reasons = [f"`{r.name}` takes {r.ratio:.2f}x" for r in over]
        reasons += [f"`{r.name}` prints otherwise than its C version" for r in differing]
        reasons += [f"`{name}` is not compiled yet" for name in missing]
        lines.append(f"The numeric programs are not within {LIMIT:g}x C: {'; '.join(reasons)}.")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    compiler, results, refused = run()
    report = markdown(compiler, results, refused)
    REPORT.write_text(report, encoding="utf-8", newline="\n")
    sys.stdout.buffer.write(report.encode("utf-8"))


if __name__ == "__main__":
    main()
