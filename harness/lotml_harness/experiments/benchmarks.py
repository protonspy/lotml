"""The phase 3 benchmarks: programs written in lotml and compiled by the C backend, against the
same programs written in C and built by the same compiler with the same options (plans/
lotml-roadmap.md, task 4.3; docs/wiki/pages/memory-model.md, "Performance target").

Numeric, allocation-heavy and sharing-heavy programs are reported apart, as the memory model
asks: the gate holds the C target to 2x C on the numeric ones, and only reports the others,
where reference counting is expected to lose to a hand-managed heap.

    python -m lotml_harness.experiments.benchmarks
"""

import json
import shutil
import subprocess
import sys
from dataclasses import dataclass

from lotml_harness import ROOT
from lotml_harness.experiments.phase1 import RESULTS

BENCHMARKS = ROOT / "harness" / "benchmarks"
REPORT = RESULTS / "benchmarks.md"
RUNS = 7
"""Runs of each program; the fastest is kept, the one least disturbed by the rest of the machine."""
LIMIT = 2.0
"""The most a numeric program may take, as a multiple of its C version (the phase 3 gate)."""
KINDS = {
    "mandelbrot": "numeric",
    "sieve": "numeric",
    "collatz": "numeric",
    "fib": "numeric",
    "matmul": "numeric",
    "binarytrees": "allocation",
    "strings": "allocation",
    "wordcount": "allocation",
    "cow": "sharing",
    "shared": "sharing",
}
TITLES = {
    "numeric": "Numeric",
    "allocation": "Allocation-heavy",
    "sharing": "Sharing-heavy",
}


@dataclass
class Result:
    name: str
    kind: str
    c: float
    """Seconds of the C version's fastest run."""
    lotml: float
    same: bool
    """Whether the two print the same."""

    @property
    def ratio(self) -> float:
        return self.lotml / self.c


def parse(lines: list[str]) -> tuple[str, list[Result]]:
    """The compiler and each benchmark's result, from the runner's JSON lines."""
    compiler, results = "", []
    for line in lines:
        row = json.loads(line)
        if "compiler" in row:
            compiler = row["compiler"]
            continue
        results.append(
            Result(
                row["name"],
                KINDS[row["name"]],
                min(row["c"]),
                min(row["lotml"]),
                row["c_out"] == row["lotml_out"],
            )
        )
    return compiler, results


def run(runs: int = RUNS) -> tuple[str, list[Result]]:
    """Every benchmark built and run by the C backend's runner, `cargo run --example bench`."""
    cargo = shutil.which("cargo")
    if cargo is None:
        raise SystemExit("cargo is not on PATH: the benchmarks are built by the C backend's runner")
    ran = subprocess.run(  # noqa: S603 - cargo, on the benchmarks of this repository
        [
            cargo,
            "run",
            "--quiet",
            "--release",
            "-p",
            "lotml-c",
            "--example",
            "bench",
            "--",
            str(BENCHMARKS),
            str(runs),
        ],
        cwd=ROOT / "compiler",
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=True,
    )
    return parse([line for line in ran.stdout.splitlines() if line.strip()])


def markdown(compiler: str, results: list[Result]) -> str:
    lines = [
        "# Benchmarks: the C target against C",
        "",
        "Generated by `python -m lotml_harness.experiments.benchmarks`. Each program in",
        "`harness/benchmarks/` is written in lotml and in C; the lotml one is compiled by the C",
        f"backend, and both are built by `{compiler}` with the options the backend's driver",
        f"uses. Each runs {RUNS} times and its fastest run is kept. The lotml programs check",
        "every integer operation and index, which the C ones do not.",
        "",
    ]
    for kind, title in TITLES.items():
        rows = [r for r in results if r.kind == kind]
        if not rows:
            continue
        lines += [f"## {title}", "", "| program | C (s) | lotml (s) | lotml / C | same output |"]
        lines.append("| --- | ---: | ---: | ---: | --- |")
        for r in rows:
            same = "yes" if r.same else "no"
            lines.append(f"| {r.name} | {r.c:.3f} | {r.lotml:.3f} | {r.ratio:.2f}x | {same} |")
        lines.append("")
    numeric = [r for r in results if r.kind == "numeric"]
    over = [r for r in numeric if r.ratio > LIMIT]
    differing = [r for r in results if not r.same]
    if numeric and not over and not differing:
        lines.append(f"The numeric programs are within {LIMIT:g}x C.")
    else:
        reasons = [f"`{r.name}` takes {r.ratio:.2f}x" for r in over]
        reasons += [f"`{r.name}` prints otherwise than its C version" for r in differing]
        lines.append(f"The numeric programs are not within {LIMIT:g}x C: {'; '.join(reasons)}.")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    compiler, results = run()
    report = markdown(compiler, results)
    REPORT.write_text(report, encoding="utf-8", newline="\n")
    sys.stdout.buffer.write(report.encode("utf-8"))


if __name__ == "__main__":
    main()
