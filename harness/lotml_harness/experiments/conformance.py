"""The conformance matrix (plans/target-parity-assurance.md, task 3.3;
docs/wiki/pages/target-parity.md, "Every test in every mode"): which language rules the LLVM
target's parity programs prove the same on both targets, and which each leaves out and why. The
rules and the programs' claims are a manifest beside the tests,
`compiler/crates/lotml-llvm/tests/conformance.json`; the programs are read from the tests
themselves, every `parity`, `panics` and `frees_everything` call, so a program missing from the
manifest, or named there and gone from the tests, is an error rather than a gap nobody counts.

    python -m lotml_harness.experiments.conformance
"""

import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

from lotml_harness import ROOT
from lotml_harness.experiments.phase1 import RESULTS

TESTS = ROOT / "compiler" / "crates" / "lotml-llvm" / "tests"
MANIFEST = TESTS / "conformance.json"
REPORT = RESULTS / "parity" / "conformance.md"
CALL = re.compile(r'\b(parity|panics|frees_everything)\(\s*"([^"]+)"')


@dataclass
class Program:
    name: str
    file: str
    """The test file, without `.rs`."""
    proves: list[str]
    leaves_out: dict[str, str]


def programs_in(tests: Path = TESTS) -> dict[str, str]:
    """Each parity program the tests run, by name, with the file it is in."""
    found: dict[str, str] = {}
    for path in sorted(tests.glob("*.rs")):
        for match in CALL.finditer(path.read_text(encoding="utf-8")):
            found.setdefault(match.group(2), path.stem)
    return found


def problems(manifest: dict, found: dict[str, str]) -> list[str]:
    """Why the manifest does not describe the tests: a program it leaves out or names wrongly, a
    rule it uses and does not declare, a program that proves nothing, a reason left empty."""
    rules = set(manifest["rules"])
    claimed = manifest["programs"]
    out = [
        f"`{n}` runs in {found[n]}.rs and the manifest does not name it"
        for n in sorted(set(found) - set(claimed))
    ]
    out += [f"`{n}` is in the manifest and in no test" for n in sorted(set(claimed) - set(found))]
    for name, claim in sorted(claimed.items()):
        if not claim["proves"]:
            out.append(f"`{name}` proves no rule")
        for rule in [*claim["proves"], *claim["leaves_out"]]:
            if rule not in rules:
                out.append(f"`{name}` names the rule `{rule}`, which the manifest does not declare")
        out += [
            f"`{name}` leaves out `{r}` without a reason"
            for r, why in claim["leaves_out"].items()
            if not why.strip()
        ]
    return out


def matrix(manifest: dict, found: dict[str, str]) -> str:
    lines = [
        "# Conformance: the language rules on both targets",
        "",
        "Generated by `python -m lotml_harness.experiments.conformance` from",
        "`compiler/crates/lotml-llvm/tests/conformance.json` and the parity programs of",
        "`compiler/crates/lotml-llvm/tests/`. A rule is proved by each program that runs it the",
        "same on the Python and the LLVM target, and left out by a program with the reason it",
        "gives.",
        "",
        "| rule | proved by | left out |",
        "| --- | --- | --- |",
    ]
    gaps = []
    rules = manifest["rules"]
    for rule, what in rules.items():
        proving = sorted(n for n, c in manifest["programs"].items() if rule in c["proves"])
        leaving = sorted(
            (n, c["leaves_out"][rule])
            for n, c in manifest["programs"].items()
            if rule in c["leaves_out"]
        )
        if not proving:
            gaps.append(rule)
        shown = ", ".join(f"`{n}`" for n in proving) or "**none**"
        left = "; ".join(f"`{n}`: {why}" for n, why in leaving)
        lines.append(f"| `{rule}`: {what} | {shown} | {left} |")
    lines += [
        "",
        f"{len(found)} programs prove {len(rules) - len(gaps)} of {len(rules)} rules.",
    ]
    if gaps:
        lines.append("No program proves " + ", ".join(f"`{r}`" for r in gaps) + ".")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    found = programs_in()
    wrong = problems(manifest, found)
    for problem in wrong:
        print(problem)
    if wrong:
        return 1
    report = matrix(manifest, found)
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(report, encoding="utf-8", newline="\n")
    sys.stdout.buffer.write(report.encode("utf-8"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
