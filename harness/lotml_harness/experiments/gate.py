"""The phase 0 gate, evaluated from the stored experiment answers.

The gate (docs/wiki/pages/evaluation-harness.md): with the reference, frontier models parse at
least 95% of their answers and leak no Python syntax; variant B is not worse than variant A, and
the indented form is not worse than the braces form, each on at least 168 paired tasks.

"Not worse" is read as: no model is significantly worse (exact McNemar, two-sided, 5%) in the
form under test, and the pooled discordant pairs do not favour the alternative. That is an absence
of evidence of harm, not a showing of equivalence: a model whose both forms are saturated adds no
information, and the pooled counts add pairs of models that answered the same tasks, so they are a
direction check, not a test.

    python -m lotml_harness.experiments.gate
"""

import json
from dataclasses import dataclass
from pathlib import Path

from lotml_harness import ROOT
from lotml_harness.experiments import editing, variants

FRONTIER = ("claude-sonnet",)
"""Models the parse and leakage criteria apply to: the frontier model the harness can reach."""
PARSE_FLOOR = 0.95
PAIRS_NEEDED = 168
ALPHA = 0.05
REPORT = ROOT / "harness" / "results" / "gate-0.md"


@dataclass
class Criterion:
    name: str
    passed: bool
    evidence: str


def rows(directory: Path) -> list[dict]:
    found: dict[tuple, dict] = {}
    for path in sorted(directory.glob("*.jsonl")):
        if path.name == editing.TASKS_FILE.name:
            continue
        for line in path.read_text(encoding="utf-8").splitlines():
            row = json.loads(line)
            key = (row["model"], row["task"], row.get("variant", row.get("form")))
            if row.get("error") is None or key not in found:
                found[key] = row
    return [r for r in found.values() if r.get("error") is None]


def comparison(summary: dict, better: str, worse: str, label: str) -> Criterion:
    """`better` is not worse than `worse` for any model, and pooled pairs do not favour `worse`."""
    against, towards, lines, enough = 0, 0, [], True
    for model, entry in summary.items():
        wins_worse, wins_better = entry[f"{worse}_only"], entry[f"{better}_only"]
        against += wins_worse
        towards += wins_better
        significant = entry["p"] < ALPHA and wins_worse > wins_better
        enough &= entry["pairs"] >= PAIRS_NEEDED
        lines.append(
            f"{model}: {entry['pairs']} pairs, {wins_better} only {better}, {wins_worse} only "
            f"{worse}, p = {entry['p']:.3f}{' (worse)' if significant else ''}"
        )
    passed = (
        bool(summary)
        and enough
        and towards >= against
        and not any(
            e["p"] < ALPHA and e[f"{worse}_only"] > e[f"{better}_only"] for e in summary.values()
        )
    )
    pooled = f"pooled: {towards} only {better}, {against} only {worse}"
    return Criterion(label, passed, "; ".join([*lines, pooled]))


def evaluate(answers: list[dict], edits: list[dict]) -> list[Criterion]:
    criteria = []
    summary = variants.summarize(answers)
    for model in FRONTIER:
        entry = summary.get(model)
        if entry is None:
            criteria.append(Criterion(f"{model} parses and does not leak", False, "no answers"))
            continue
        b = entry["b"]
        rate = b["parsed"] / b["answers"] if b["answers"] else 0.0
        criteria.append(
            Criterion(
                f"{model} parses at least {PARSE_FLOOR:.0%} in variant B",
                rate >= PARSE_FLOOR,
                f"{b['parsed']} of {b['answers']} ({rate:.1%})",
            )
        )
        criteria.append(
            Criterion(
                f"{model} leaks no Python syntax in variant B",
                b["leaked"] == 0,
                f"{b['leaked']} answers with a leaked construct",
            )
        )
    criteria.append(comparison(summary, "b", "a", "variant B is not worse than variant A"))
    edit_summary = editing.summarize(edits)
    criteria.append(
        comparison(edit_summary, "indented", "braces", "the indented form is not worse than braces")
    )
    return criteria


def markdown(criteria: list[Criterion]) -> str:
    lines = [
        "# Phase 0 gate",
        "",
        "Generated by `python -m lotml_harness.experiments.gate` from the stored answers in",
        "`harness/results/variants/` and `harness/results/editing/`. The parse and leakage",
        "criteria count every stored variant B answer of the frontier model, including those",
        "written outside the paired sample to seed the editing tasks; the comparisons count",
        'paired tasks only. "Not worse" means no model significantly worse (exact McNemar,',
        "5%) and the pooled discordant pairs, a direction check rather than a test, not",
        "favouring the alternative: no evidence of harm, not a showing of equivalence.",
        "",
        "| criterion | result | evidence |",
        "| --- | --- | --- |",
    ]
    for c in criteria:
        lines.append(f"| {c.name} | {'pass' if c.passed else 'fail'} | {c.evidence} |")
    verdict = "passes" if all(c.passed for c in criteria) else "does not pass"
    lines += ["", f"The gate {verdict}."]
    return "\n".join(lines) + "\n"


def main() -> None:
    criteria = evaluate(rows(variants.RUNS), rows(editing.RUNS))
    REPORT.write_text(markdown(criteria), encoding="utf-8")
    print(REPORT.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
